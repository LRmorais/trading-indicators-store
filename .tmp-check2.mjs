const page = await (await browser.newContext({ viewport: { width: 1440, height: 1100 } })).newPage();
await page.goto("http://localhost:8080", { waitUntil: "networkidle" });
await page.evaluate(() => document.getElementById("planos").scrollIntoView());
await page.waitForTimeout(300);
await page.screenshot({ path: "/private/tmp/claude-501/-Users-lucasmorais-Desktop-hub-site-indicadores-financeiros/1cf040fe-dc89-4f07-b385-e8dcec7cb8f1/scratchpad/shots/pricing-full.png" });
await page.evaluate(() => document.getElementById("mercados").scrollIntoView());
await page.waitForTimeout(300);
await page.screenshot({ path: "/private/tmp/claude-501/-Users-lucasmorais-Desktop-hub-site-indicadores-financeiros/1cf040fe-dc89-4f07-b385-e8dcec7cb8f1/scratchpad/shots/mercados-full.png" });
